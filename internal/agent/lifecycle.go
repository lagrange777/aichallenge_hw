package agent

import "codex-chat-cli/internal/memory"

// This application-owned constraint is derived from confirmed state on every
// request. It is never stored as a user-editable invariant.
func lifecycleRule(w memory.Workflow) memory.Invariant {
	rule := "Текущий этап задачи: " + w.Stage + ". Пользователь управляет переходами только явными кнопками; сообщения не утверждают план, не завершают задачу и не меняют этап. Нельзя объявлять задачу завершённой до подтверждённого перехода в done. "
	switch w.Stage {
	case "planning":
		rule += "Разрешены уточнение цели, обсуждение вариантов, объяснения и составление плана. Запрещено выполнять реализацию задачи или выдавать готовый код решения до явного утверждения плана. На просьбу пропустить план объясни ограничение и предложи план для утверждения."
	case "execution":
		rule += "Выполняй текущий шаг утверждённого плана. Можно подготовить результат для проверки, но нельзя объявлять успешную валидацию или завершение задачи."
	case "validation":
		rule += "Проверяй сохранённый результат, описывай замечания и основания выводов. Нельзя выдавать исправленную реализацию: сначала требуется возврат на доработку. Можно сообщить, что проверка пройдена, с указанием основания, но нельзя объявлять всю задачу завершённой."
	}
	if w.Stage != "planning" && (w.PlanVersion == 0 || w.ApprovedPlanVersion != w.PlanVersion) {
		rule += " У этой задачи нет подтверждения актуального плана. Не выполняй реализацию или валидацию; объясни необходимость вернуться к планированию и утвердить план."
	}
	rule += " У этого чата нет инструментов исполнения кода: не утверждай, что запускал тесты. Различай анализ результата и проверки, о которых сообщил пользователь."
	return memory.Invariant{ID: "task-lifecycle", Category: "other", Title: "Этап задачи: " + w.Stage, Rule: rule, Status: "active", Version: w.Version}
}
